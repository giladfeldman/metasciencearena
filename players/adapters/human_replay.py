"""Replay adapter for HUMAN evaluators (T6 human evaluation, 2026-09-28).

A person answers a revealed-split task on the website; the answer is stored in
Neon. To score it with the arena's OWN scorer -- the same code path, the same
record shape, the same instrument/provenance blocks as every tool and LLM --
``tools/human_score.py`` exports the answers and runs the ordinary
``run_tournament()`` with one registry entry per person, each using this adapter.
The adapter does no judging of its own: it hands back what the person submitted.

The one thing it checks is that the person SAW the task being scored. The web
app records ``input_sha256`` -- the digest of the canonical JSON of the task
input it rendered (``leaderboard-app/lib/human/canonical.ts``). The runner hands
this adapter the envelope regenerated by the arena generator. If the two differ,
the person answered different content than the scorer would grade them on, and
the adapter raises instead of returning a number: an honest error record beats a
plausible score against the wrong task.

Responses file (written by tools/human_score.py, never committed)::

    {"<task_id>": {"answer": {...}, "input_sha256": "<hex>"}, ...}
"""
from __future__ import annotations

import hashlib
import json
from decimal import Decimal
from pathlib import Path

from framework.player_adapter import (
    VERSION_ABSENT_BY_DESIGN,
    PlayerAdapter,
    VersionAbsence,
    register_adapter_class,
)


def _js_number(x: float) -> str:
    """Format a float exactly as JavaScript's ``Number.prototype.toString`` does.

    Needed because the two sides disagree on NOTATION, not value: Python writes
    ``1.0`` / ``1e-07`` where JavaScript writes ``1`` / ``1e-7``. Both emit the
    shortest round-tripping digits, so only the layout rules (ECMA-262
    Number::toString) are re-applied here.
    """
    if x == 0:
        return "0"
    sign = "-" if x < 0 else ""
    digits_t = Decimal(repr(abs(x))).as_tuple()
    digits = "".join(map(str, digits_t.digits)).rstrip("0") or "0"
    exp = digits_t.exponent + (len(digits_t.digits) - len(digits))
    k = len(digits)
    n = k + exp  # position of the decimal point relative to the digit string
    if k <= n <= 21:
        body = digits + "0" * (n - k)
    elif 0 < n <= 21:
        body = digits[:n] + "." + digits[n:]
    elif -6 < n <= 0:
        body = "0." + "0" * (-n) + digits
    else:
        e = n - 1
        mant = digits if k == 1 else digits[0] + "." + digits[1:]
        body = f"{mant}e{'+' if e >= 0 else '-'}{abs(e)}"
    return sign + body


def _canonical(value) -> str:
    if value is None or isinstance(value, bool):
        return json.dumps(value)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if value != value or value in (float("inf"), float("-inf")):
            raise ValueError("non-finite number in a task input")
        return _js_number(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (list, tuple)):
        return "[" + ",".join(_canonical(v) for v in value) + "]"
    if isinstance(value, dict):
        # Sort by UTF-16 code units, as JavaScript's default sort compares.
        keys = sorted(value, key=lambda k: k.encode("utf-16-be"))
        return "{" + ",".join(json.dumps(k, ensure_ascii=False) + ":" + _canonical(value[k])
                              for k in keys) + "}"
    raise TypeError(f"not JSON: {type(value).__name__}")


def canonical_input_sha256(task_input: dict) -> str:
    """sha256 of the task input as sorted-key, compact, non-ASCII-escaped JSON.

    MUST stay byte-identical to ``canonicalInputSha256`` in
    ``leaderboard-app/lib/human/canonical.ts``. Both sides are pinned to the same
    vectors (``leaderboard-app/lib/__tests__/fixtures/human-canonical-vectors.json``)
    by players/adapters/tests/test_human_replay.py and
    leaderboard-app/lib/__tests__/human-canonical.test.ts.
    """
    return hashlib.sha256(_canonical(task_input).encode("utf-8")).hexdigest()


class ShownInputMismatch(RuntimeError):
    """The task the person saw is not the task the generator regenerates."""


class HumanReplayAdapter(PlayerAdapter):
    """Return a human evaluator's stored answer for a task."""

    def __init__(self, *args, responses_path: str | Path, **kwargs):
        super().__init__(*args, **kwargs)
        self.responses_path = Path(responses_path)
        self._responses: dict[str, dict] | None = None

    def prepare(self) -> None:
        self._responses = json.loads(self.responses_path.read_text(encoding="utf-8"))

    def play_task(self, envelope: dict, *, timeout_s: int) -> dict:
        if self._responses is None:
            self.prepare()
        assert self._responses is not None
        task_id = envelope["task_id"]
        entry = self._responses.get(task_id)
        if entry is None:
            raise KeyError(f"no stored human answer for {task_id}")
        shown = entry.get("input_sha256")
        regenerated = canonical_input_sha256(envelope.get("input", {}))
        if shown != regenerated:
            raise ShownInputMismatch(
                f"{task_id}: the page showed input {str(shown)[:12]}..., the generator "
                f"regenerates {regenerated[:12]}...; refusing to score against content "
                "the person did not see")
        return entry["answer"]

    def version_absence_reason(self) -> VersionAbsence:
        return VersionAbsence(
            VERSION_ABSENT_BY_DESIGN,
            "a human evaluator has no software version; the instrument is the person",
        )


register_adapter_class("HumanReplayAdapter", HumanReplayAdapter)
