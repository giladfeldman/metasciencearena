"""Per-item analysis of a citation-claim-fidelity-v1 run, and the pass-bar verdict.

Held-out records are redacted (no output), so item verdicts are recovered from
the raw provider responses (article custody for held-out tasks, beside the run
file for public ones) and the gold is regenerated by the arena generator. The
guard is the scorer's own (`scorer.guarded_verdicts`), so a verdict here is the
verdict that was scored.

A run with errored records (a call that produced no answer) is INCOMPLETE: the
bars are not evaluated on it; re-run the failed tasks first. Nothing is excused
silently and nothing is counted as zero for an infrastructure reason. An errored
record whose call returned the model's answer (its raw response is stored) is
NOT an errored call: it is read through the scorer's guard, and what cannot be
read is no verdict (owner decision 2026-10-15; the citeclaim library's llm_malformed).

    python arenas/citation-claim-fidelity-v1/tools/analyze_run.py --run-file <jsonl>
        --split private|revealed [--seed N] [--grouping <grouping.json>] [--out <custody json>]
        [--task-set v3 --tier synthetic|rd-zhang2024|rd-scifact-dev]

Task set v3 holds several tiers; --tier scores ONE of them (its tasks only are expected,
and its own bars apply: the synthetic tier's pass_bars, or pass_bars.real_data_tiers.<tier>).
`--write-tasks-file <custody path> --tier T` writes that tier's task ids for `framework run
--tasks-file` and exits.

Output (stdout): counts and rates only, never text.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ARENA = Path(__file__).resolve().parents[1]
REPO = ARENA.parents[1]
sys.path.insert(0, str(REPO))
from framework import run_env, timeouts  # noqa: E402


def _load(name):
    spec = importlib.util.spec_from_file_location(f"ccf_an_{name}", ARENA / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


scorer, bars, generator = _load("scorer"), _load("bars"), _load("generator")


def raw_text(raw) -> str | None:
    """The answer text inside a stored provider response (OpenAI-style or Gemini)."""
    if not isinstance(raw, dict):
        return None
    if raw.get("choices"):
        return ((raw["choices"][0] or {}).get("message") or {}).get("content")
    if raw.get("candidates"):
        parts = ((raw["candidates"][0] or {}).get("content") or {}).get("parts") or []
        return "".join(p.get("text", "") for p in parts if not p.get("thought"))
    return None


def parse_output(text: str | None):
    if not text:
        return None
    from framework.player_adapter import _extract_json_value
    try:
        return _extract_json_value(text)
    except Exception:
        return None


def private_seed(version: str = "v1") -> int:
    return int((ARENA / "task_sets" / version / ".private_seed").read_text(encoding="utf-8").strip())


def tier_gold(version: str, seed: int, split: str, tier: str | None) -> dict:
    """task_id -> gold for one split (and, on a tiered task set, one tier)."""
    gold = {}
    for env in generator.generate(version, seed, split=split):
        gt = generator.ground_truth(env["task_id"])
        if tier is None or gt.get("tier", "synthetic") == tier:
            gold[env["task_id"]] = gt
    return gold


def item_results(run_file: Path, split: str, seed: int, version: str = "v1",
                 tier: str | None = None) -> tuple[list[dict], dict]:
    recs = [json.loads(l) for l in run_file.read_text(encoding="utf-8").splitlines() if l.strip()]
    other = {r.get("task_set_version") for r in recs} - {version}
    if other:
        raise SystemExit(f"run file holds task set(s) {sorted(other)}, not {version}: pass --task-set")
    held_out = split == "private"
    raw_path = run_env.raw_sidecar_path(run_file, held_out=held_out, arena_id="citation-claim-fidelity-v1")
    raws = {r["run_id"]: r["raw_response"] for r in (run_env.read_raw(raw_path) if raw_path.exists() else [])}
    gold = tier_gold(version, seed, split, tier)
    # Cohort (reported, never barred): a v2 task that is also a v1 task is "v1-core";
    # the rest is the 2026-10-15 C1 top-up. Same seed and task_key give the same id.
    core = set(gold)
    if version != "v1" and split == "private":
        core = {e["task_id"] for e in generator.generate("v1", seed, split=split)}
        generator._GROUND_TRUTH_CACHE.update(gold)  # generating v1 refilled the shared cache
    from framework.runner import _canonical_sha256
    items, meta, served = [], Counter(), Counter()
    # One record per task, one player (consult 2026-10-15): a re-run appended to the
    # file counted a task twice and could lift a type over min_n or its recall bar.
    meta["instrument_variants"] = len({instrument_key(r) for r in recs})
    per_task = Counter(r["task_id"] for r in recs)
    meta["duplicate_records"] = sum(n - 1 for n in per_task.values() if n > 1)
    meta["players"] = len({r.get("player_id") for r in recs})
    for r in recs:
        meta["records"] += 1
        err = (r.get("score") or {}).get("breakdown", {}).get("error")
        # Owner decision 2026-10-15: an errored record whose call RETURNED the model's
        # answer (the arena schema rejected it, e.g. a bare list where {"items": [...]}
        # is required, or the adapter could not parse it) is an answer, not a failed
        # call. It is read through the same guard as every answer, so whatever the
        # citeclaim library would keep is kept and the rest is no verdict (llm_malformed);
        # it is neither excluded nor re-sampled. The answer is known to exist from its
        # stored raw response: the runner keeps one for every call that got an HTTP
        # answer and none for a 429 / 5xx / timeout (measured 2026-10-15: 0 of 97
        # quota errors, 28 of 28 schema violations). Only calls without one are errored.
        # A transport failure (our clock, a 429/5xx) is never an answer, even with a
        # raw beside it: a container call that raised could keep the PREVIOUS task's
        # raw under this run_id (consult 2026-10-19).
        answered = (err is not None and r.get("run_id") in raws
                    and not timeouts.is_transport_failure(err))
        if err is not None and not answered:
            meta["errored"] += 1
            continue
        gt = gold.get(r["task_id"])
        if gt is None:
            # A record of another tier of the same task set is not this tier's to score;
            # it is counted (and keeps the run incomplete) so a mixed file is visible.
            meta["unknown_task" if tier is None or r["task_id"] not in _all_ids(version, seed, split)
                 else "other_tier_task"] += 1
            continue
        # The verdicts are zipped onto TODAY's gold, so it must be the gold the record
        # was scored against (consult 2026-10-15: a rebuilt task set would re-score old
        # answers against new items without a word).
        if (r.get("instrument") or {}).get("gold_sha256") != _canonical_sha256(gt):
            meta["gold_mismatch"] += 1
            continue
        out = parse_output(raw_text(raws.get(r["run_id"])))
        if answered:
            meta["answered_with_error"] += 1
        else:
            if out is None and not held_out:
                out = r.get("output")
            if out is None:
                meta["no_raw"] += 1
                continue
        # Reported, never barred (consult 2026-10-15): a floating alias can change the
        # served model between days of one repeat.
        served[str((r.get("response_meta") or {}).get("served_model"))] += 1
        verdicts = scorer.guarded_verdicts(out, len(gt["items"]), gt["abstract"])
        cluster = hashlib.sha256(gt["abstract"].encode("utf-8")).hexdigest()[:12]
        t = gt.get("tier", "synthetic")
        for g, v in zip(gt["items"], verdicts):
            cohort = (("v1-core" if r["task_id"] in core else "v2-c1-topup") if t == "synthetic"
                      else str((g.get("meta") or {}).get("source", t)))
            items.append({"task_id": r["task_id"], "id": g["id"], "type": g["type"], "gold": g["gold"],
                          "verdict": v, "cluster": cluster, "group_size": len(gt["items"]), "tier": t,
                          "cohort": cohort, "correct": scorer.is_correct(g["gold"], v),
                          "explanation": (g.get("meta") or {}).get("explanation")})
    meta["tasks_expected"] = len(gold)
    meta["tasks_scored"] = len({it["task_id"] for it in items})
    out_meta = dict(meta)
    out_meta["served_models"] = dict(served)
    return items, out_meta


_CALL_CONFIGS: dict = {}


def instrument_key(rec: dict) -> str:
    """Everything that defines the instrument of one record, minus the task's group size.

    Sol, consult 2026-10-18: a file under one player_id could mix prompt or inference
    settings and still read complete. The record's call_config (read off the request
    actually sent, run_env/call_configs/) differs across tasks only by group_size, so
    that key is dropped; a record whose call_config file is missing is its own variant.
    """
    h = rec.get("call_config_sha256")
    if h not in _CALL_CONFIGS:
        path = REPO / "run_env" / "call_configs" / f"{h}.json"
        cfg = json.loads(path.read_text(encoding="utf-8")) if h and path.exists() else {"missing": h}
        cfg.pop("group_size", None)
        _CALL_CONFIGS[h] = json.dumps(cfg, sort_keys=True)
    return json.dumps([_CALL_CONFIGS[h], rec.get("env_sha"), (rec.get("instrument") or {}).get("scorer_sha256"),
                       rec.get("player_identity"), rec.get("player_version"), rec.get("player_id")], sort_keys=True)


_ALL_IDS: dict = {}


def _all_ids(version: str, seed: int, split: str) -> set:
    key = (version, seed, split)
    if key not in _ALL_IDS:
        _ALL_IDS[key] = {e["task_id"] for e in generator.generate(version, seed, split=split)}
    return _ALL_IDS[key]


def precision_at_prevalence(items: list[dict], prevalences=(0.05, 0.10, 0.20)) -> dict:
    clean = [it for it in items if it["gold"] == "consistent"]
    contra = [it for it in items if it["type"] in ("A4", "A2", "C1", "C3")]
    if not clean or not contra:
        return {}
    fa = sum(it["verdict"] == "contradicts" for it in clean) / len(clean)
    rec = sum(it["verdict"] == "contradicts" for it in contra) / len(contra)
    out = {}
    for p in prevalences:
        tp, fp = p * rec, (1 - p) * fa
        out[str(p)] = round(tp / (tp + fp), 4) if tp + fp else None
    return {"false_alarm_rate": round(fa, 4), "pooled_recall_A4_A2_C1_C3": round(rec, 4), "precision": out}


def tier_report(items: list[dict], tier: str) -> dict:
    """Reported, never barred: verdict counts per gold class, overall and per label source;
    for rd-zhang2024 also discrimination (pooled and within source), the 'contradicts'-only
    rate on Unsubstantiated and precision of 'contradicts' at assumed prevalences."""
    def counts(its):
        out = defaultdict(Counter)
        for it in its:
            out[it["gold"]][str(it["verdict"])] += 1
        return {g: dict(c) for g, c in sorted(out.items())}
    by_src = defaultdict(list)
    for it in items:
        by_src[it["cohort"]].append(it)
    expl = Counter((it["gold"], str(it["explanation"]), str(it["verdict"])) for it in items if it.get("explanation"))
    rep = {"verdicts_by_gold": counts(items),
           "verdicts_by_gold_per_source": {s: counts(its) for s, its in sorted(by_src.items())},
           "verdicts_by_explanation": [{"gold": g, "explanation": e, "verdict": v, "n": n}
                                       for (g, e, v), n in sorted(expl.items())],
           "abstracts_per_gold": {g: len({it["cluster"] for it in items if it["gold"] == g})
                                  for g in sorted({it["gold"] for it in items})}}
    if tier == "rd-zhang2024":
        spec = {"verdict": "consistent", "gold_high": "not_contradicts", "gold_low": "not_consistent"}
        rep["discrimination_pooled"] = bars.discrimination(items, spec)
        rep["discrimination_within_source"] = {s: bars.discrimination(its, spec) for s, its in sorted(by_src.items())}
        full = [it for it in items if it["gold"] == "not_contradicts"]
        unsub = [it for it in items if it["gold"] == "not_consistent"]
        fa = sum(it["verdict"] == "contradicts" for it in full) / len(full) if full else None
        rec = sum(it["verdict"] == "contradicts" for it in unsub) / len(unsub) if unsub else None
        rep["contradicts_on_unsubstantiated"] = [sum(it["verdict"] == "contradicts" for it in unsub), len(unsub)]
        if fa is not None and rec is not None:
            rep["precision_at_prevalence"] = {
                "false_alarm_rate": round(fa, 4), "contradicts_recall_on_unsubstantiated": round(rec, 4),
                "precision": {str(p): (round(p * rec / (p * rec + (1 - p) * fa), 4) if p * rec + (1 - p) * fa else None)
                              for p in (0.05, 0.10, 0.20)}}
    return rep


def summarize(items: list[dict], meta: dict, grouping: dict | None, tier: str | None = None) -> dict:
    by_type = defaultdict(lambda: [0, 0])
    for it in items:
        by_type[it["type"]][0] += it["correct"]
        by_type[it["type"]][1] += 1
    summary = {
        "meta": meta,
        "n_items": len(items),
        "accuracy": round(sum(it["correct"] for it in items) / len(items), 4) if items else None,
        "accuracy_by_type": {t: {"correct": c, "n": n, "rate": round(c / n, 4)} for t, (c, n) in sorted(by_type.items())},
        "verdict_counts": dict(Counter(str(it["verdict"]) for it in items)),
    }
    real = tier not in (None, "synthetic")
    if not real:
        summary["precision_at_prevalence"] = precision_at_prevalence(items)
    # Reported, never barred (consult 2026-10-15): v2 added an easier, selected C1
    # population and more clean items, so the unchanged bars are shown per cohort too.
    cohorts = defaultdict(list)
    for it in items:
        cohorts[it.get("cohort", "v1-core")].append(it)
    summary["by_cohort"] = {}
    # Sonnet, consult 2026-10-18: these synthetic-tier summaries count gold 'consistent' /
    # 'silent' and C1 only, so on a real tier they printed [0, 0] that read as "no false
    # alarms". A real tier reports tier_report instead.
    for name, its in ([] if real else sorted(cohorts.items())):
        clean = [it for it in its if it["gold"] == "consistent"]
        c1 = [it for it in its if it["type"] == "C1"]
        summary["by_cohort"][name] = {
            "n_items": len(its),
            "accuracy": round(sum(it["correct"] for it in its) / len(its), 4),
            "clean_false_alarm": [sum(it["verdict"] == "contradicts" for it in clean), len(clean)],
            "c1_recall": [sum(it["verdict"] == "contradicts" for it in c1), len(c1)]}
    # Reported, never barred (consult 2026-10-15, Sonnet #2): no-verdict items stay in
    # the pre-registered false-alarm denominators, which lowers the rates; the rate
    # over items that HAVE a verdict is shown beside them.
    summary["false_alarm_answered_only"] = {} if real else {
        g: [sum(it["verdict"] == "contradicts" for it in items if it["gold"] == g),
            sum(it["verdict"] is not None for it in items if it["gold"] == g)]
        for g in ("consistent", "silent")}
    complete = all(meta.get(k, 0) == 0 for k in ("errored", "no_raw", "unknown_task", "duplicate_records",
                                                   "gold_mismatch", "other_tier_task")) \
        and meta.get("instrument_variants") == 1 \
        and meta.get("players") == 1 and meta.get("tasks_scored") == meta.get("tasks_expected")
    summary["complete"] = complete
    if real:
        summary["tier"] = tier
        summary["tier_report"] = tier_report(items, tier)
    if not complete:
        summary["bars"] = {"passed": None, "checks": [],
                           "detail": "run incomplete: bars not evaluated (re-run failed tasks first)"}
    elif real:
        summary["bars"] = bars.evaluate_tier(items, bars.load_tier_bars(tier))
    else:
        summary["bars"] = bars.evaluate(items, grouping=grouping)
    return summary


def grouping_for_bars(g: dict, *, player: str, task_set: str, run_file_sha256: str) -> tuple[dict | None, str | None]:
    """The grouping-probe summary, if it is complete and belongs to THIS run; else (None, why).

    Consult 2026-10-15 (Sonnet + Sol): a probe with errored or missing pairs, a
    --max-tasks subset, another player's or task set's probe, or one built from a
    different run file all satisfied the grouping bar. A rejected probe leaves the
    bar FAILING ("no paired grouping result"); nothing passes by omission.
    """
    checks = [("mean_difference" in g and "ci95_lower" in g, "no paired result"),
              (g.get("player") == player, f"probe player {g.get('player')!r} is not {player!r}"),
              (g.get("task_set") == task_set, f"probe task set {g.get('task_set')!r} is not {task_set!r}"),
              (g.get("run_file_sha256") == run_file_sha256, "probe was built from a different run file"),
              (g.get("max_tasks") is None, "probe ran on a --max-tasks subset"),
              (g.get("n_errored") == 0, f"{g.get('n_errored')} single-sentence calls errored (re-run them)"),
              (g.get("n_missing_grouped") == 0, f"{g.get('n_missing_grouped')} items had no grouped verdict"),
              (g.get("n_expected") is not None and g.get("n") == g.get("n_expected"),
               f"{g.get('n')} of {g.get('n_expected')} expected pairs")]
    for ok, why in checks:
        if not ok:
            return None, why
    return g, None


def _require_custody(path: Path, split: str) -> None:
    if split == "private":
        custody = run_env.raw_sidecar_path(Path("x.jsonl"), held_out=True, arena_id="x").parents[3]
        if custody not in path.resolve().parents:
            raise SystemExit(f"output for the private split must be inside article custody ({custody})")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-file", type=Path)
    ap.add_argument("--split", required=True, choices=["private", "revealed"])
    ap.add_argument("--seed", type=int)
    ap.add_argument("--task-set", default="v1", choices=list(generator.KNOWN_TASK_SET_VERSIONS))
    ap.add_argument("--grouping", type=Path)
    ap.add_argument("--out", type=Path, help="write per-item results (custody path only for private)")
    ap.add_argument("--tier", choices=list(generator.TIERS))
    ap.add_argument("--write-tasks-file", type=Path, help="write the --tier's task ids (custody path) and exit")
    a = ap.parse_args()
    tiered = a.task_set not in ("v1", "v2")
    if tiered and not a.tier:
        raise SystemExit(f"task set {a.task_set} holds several tiers: pass --tier")
    if a.tier and not tiered:
        raise SystemExit(f"task set {a.task_set} has no tiers")
    seed = a.seed if a.seed is not None else (private_seed(a.task_set) if a.split == "private" else 0)
    if a.write_tasks_file:
        _require_custody(a.write_tasks_file, a.split)
        ids = sorted(tier_gold(a.task_set, seed, a.split, a.tier))
        a.write_tasks_file.parent.mkdir(parents=True, exist_ok=True)
        a.write_tasks_file.write_text("\n".join(ids) + "\n", encoding="utf-8")
        print(json.dumps({"tier": a.tier, "n_task_ids": len(ids)}))
        return 0
    if a.run_file is None:
        raise SystemExit("--run-file is required")
    items, meta = item_results(a.run_file, a.split, seed, a.task_set, a.tier)
    run_sha = hashlib.sha256(a.run_file.read_bytes()).hexdigest()
    meta["run_file_sha256"] = run_sha
    meta["task_set"] = a.task_set
    meta["tier"] = a.tier
    player = json.loads(a.run_file.read_text(encoding="utf-8").splitlines()[0])["player_id"]
    meta["player_id"] = player
    grouping, rejected = None, None
    if a.grouping:
        doc = json.loads(a.grouping.read_text(encoding="utf-8"))
        grouping, rejected = grouping_for_bars(doc.get("summary", doc), player=player, task_set=a.task_set,
                                               run_file_sha256=run_sha)
    summary = summarize(items, meta, grouping, a.tier)
    if rejected:
        summary["grouping_rejected"] = rejected
    if a.out:
        _require_custody(a.out, a.split)
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(json.dumps({"summary": summary, "items": items}, indent=1), encoding="utf-8")
    print(json.dumps(summary, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
